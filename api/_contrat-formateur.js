const blanc = (v) => (v && String(v).trim() ? String(v).trim() : '…');
const FORMES = { ei: 'entreprise individuelle', micro: 'entreprise individuelle (micro-entreprise)', eurl: 'EURL', sarl: 'SARL', sasu: 'SASU', sas: 'SAS', autre: '' };

// Le paragraphe d'identité du formateur, à la place des blancs du modèle.
export function phraseIdentite(id = {}) {
  const forme = FORMES[id.forme] || id.forme_libre || '';
  const societe = !['ei', 'micro'].includes(id.forme);
  return [
    `${societe ? 'La société' : "L'entreprise individuelle"} ${blanc(id.raison_sociale)}`,
    forme ? ` (forme juridique : ${forme})` : '',
    societe && id.capital ? `, au capital de ${id.capital} euros` : '',
    `, dont le siège social est situé ${blanc(id.siege)}`,
    `, immatriculée ${id.immatriculation ? `au ${id.immatriculation}` : 'au répertoire national des entreprises'} sous le numéro ${blanc(id.siret)} (SIRET)`,
    `, représentée par ${blanc(id.representant)} en sa qualité ${/^[aeiouyéèêh]/i.test(blanc(id.qualite)) ? "d'" : 'de '}${blanc(id.qualite)}, dûment habilité(e) aux fins des présentes,`,
  ].join('');
}
export function phraseRegime(regime, nda) {
  const c = (k) => (regime === k ? '☒' : '☐');
  return `Le Formateur indique ci-après son régime : ${c('exonere')} exonéré de TVA (NDA n° ${regime === 'exonere' && nda ? nda : '…'})   ${c('assujetti')} assujetti à la TVA   ${c('franchise')} franchise en base (art. 293 B du CGI). Il informe le Donneur d'ordre par écrit de tout changement de régime dans un délai de quinze (15) jours.`;
}

// Le contrat rempli, en blocs { k, x } : la page l'affiche, le serveur en calcule l'empreinte.
export function contratRempli(f = {}, signature = null) {
  const id = f.identite || {};
  return BLOCS.map((b) => {
    if (b.k === 'identite') return { k: 'p', x: phraseIdentite({ ...id, siret: f.siret || id.siret }) };
    if (b.k === 'regime') return { k: 'p', x: phraseRegime(f.regime_tva, f.nda) };
    if (b.k === 'intervenants') return { k: 'li', x: `${b.avant} ${blanc(f.intervenants || id.representant)}${b.apres}` };
    if (b.k === 'fait_a') {
      const date = signature ? new Date(signature.date).toLocaleDateString('fr-FR', { timeZone: 'Europe/Paris', day: '2-digit', month: '2-digit', year: 'numeric' }) : '…';
      return { k: 'p', x: `Fait à ${blanc(signature && signature.lieu)}, le ${date}, et signé électroniquement par les Parties.` };
    }
    if (b.k === 'signatures') {
      return { k: 'signatures', donneur: "CLINDIT (IA-Entrepreneur), représentée par Gabriel VANDERBECKEN, Président", formateur: `${blanc(id.raison_sociale)}, représenté(e) par ${blanc(id.representant)}` };
    }
    return b;
  });
}
export function texteContrat(blocs) {
  return blocs.map((b) => (b.k === 'tableau' ? b.lignes.map((l) => l.join(' | ')).join('\n') : b.k === 'signatures' ? `Pour le Donneur d'ordre : ${b.donneur}\nPour le Formateur : ${b.formateur}` : b.x)).join('\n');
}
